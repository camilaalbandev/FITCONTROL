create table if not exists public.planos (
    id bigint generated by default as identity primary key,
    nome varchar(120) not null,
    valor numeric(10,2) not null check (valor >= 0),
    duracao_meses integer not null check (duracao_meses > 0)
);

create table if not exists public.alunos (
    id bigint generated by default as identity primary key,
    nome varchar(160) not null,
    cpf varchar(20) not null unique,
    telefone varchar(30),
    idade integer,
    endereco varchar(255),
    data_matricula date,
    status varchar(20) not null default 'ATIVO',
    plano_id bigint references public.planos(id) on delete set null
);

create table if not exists public.professores (
    id bigint generated by default as identity primary key,
    nome varchar(160) not null,
    cpf varchar(20) not null unique,
    telefone varchar(30),
    idade integer,
    cref varchar(40),
    especialidade varchar(120),
    horario_trabalho varchar(120)
);

create table if not exists public.pagamentos (
    id bigint generated by default as identity primary key,
    aluno_id bigint not null references public.alunos(id) on delete cascade,
    valor numeric(10,2) not null check (valor >= 0),
    vencimento date not null,
    status varchar(20) not null default 'PENDENTE'
);

